/** An opened list: generated ("generated") or mixed ("mixed"); both play through the shared queue. */
data class HomeDetail(
    val kind: String, val id: String, val title: String, val description: String = "", val cover: String? = null,
    val weekly: Boolean = false, val state: String = "ready", val updated: Long? = null, val notice: String? = null,
    val songs: List<Song> = emptyList(), val loading: Boolean = true,
)

@HiltViewModel
class HomeViewModel @Inject constructor(
    private val api: MusicApi, private val prefs: PreferencesRepository,
    private val library: LibraryRepository, val player: MusicPlayer,
    private val offline: com.armonia.app.offline.OfflineManager, private val streamCache: com.armonia.app.playback.StreamCache,
) : ViewModel() {
    private val owner = prefs.cachedUserId
    var recent by mutableStateOf<List<RecentPlaylist>>(emptyList()); private set
    var generated by mutableStateOf<List<GeneratedPlaylist>>(emptyList()); private set
    var status by mutableStateOf<HomeStatus?>(null); private set
    var artists by mutableStateOf<List<HomeArtist>>(emptyList()); private set
    var frequent by mutableStateOf<List<Album>>(emptyList()); private set
    var newest by mutableStateOf<List<Album>>(emptyList()); private set
    var detail by mutableStateOf<HomeDetail?>(null); private set
    var loaded by mutableStateOf(false); private set
    /** The last attempt to load the lists did not reach the server (no network, VPN off). */
    var unreachable by mutableStateOf(false); private set
    var busy by mutableStateOf(false); private set
    var message by mutableStateOf<String?>(null)
    private var polling = false

    var onPhone by mutableStateOf<List<Song>>(emptyList()); private set
    var savedLists by mutableStateOf<List<com.armonia.app.offline.OfflineCollection>>(emptyList()); private set
    private val account = prefs.accountNamespace

    @OptIn(kotlinx.coroutines.FlowPreview::class)
    suspend fun loadOnPhone() {
        val saved = library.savedSongMetadata(account).associateBy { it.id }.toMutableMap()
        var lookedUp = emptySet<String>()
        val inventory = streamCache.inventoryChanges.debounce(200).map { streamCache.completeLibraryIds(account) }
            .distinctUntilChanged()
        combine(offline.catalog, offline.progress, inventory, prefs.authState) { catalog, _, cached, auth ->
            Triple(catalog, cached, auth.namespace)
        }.collectLatest { (catalog, cached, namespace) ->
            if (account != namespace || account != prefs.accountNamespace) {
                onPhone = emptyList()
                savedLists = emptyList()
                if (detail?.kind == "phone") close()
                return@collectLatest
            }
            val pinned = offline.cachedSongIds(catalog.allSongs())
            val available = pinned + cached
            val known = saved + player.queue.value.associateBy { it.id } + catalog.allSongs().associateBy { it.id }
            fun publish(metadata: Map<String, Song>) {
                if (account != prefs.accountNamespace) return
                onPhone = songsOnPhone(available, metadata)
                savedLists = catalog.collections.filter { it.key.startsWith("playlist:") && it.songs.any { s -> s.id in available } }
                detail?.takeIf { it.kind == "phone" }?.let { openOnPhone(it.id) }
            }
            publish(known)
            val missing = cached - known.keys
            if (missing.isNotEmpty() && missing != lookedUp) {
                library.getSongs().onSuccess { songs ->
                    saved.putAll(songs.associateBy { it.id })
                    publish(known + saved)
                }
                lookedUp = missing
            }
        }
    }

    fun openOnPhone(id: String) {
        if (account != prefs.accountNamespace) return close()
        val list = savedLists.firstOrNull { it.key == id }
        val songs = if (id == "all") onPhone else {
            if (list == null) return close()
            val ids = onPhone.mapTo(HashSet()) { it.id }
            list.songs.filter { it.id in ids }
        }
        detail = HomeDetail("phone", id, list?.title ?: "Tus canciones sin conexion",
            cover = list?.coverArt?.let { art(it) }, songs = songs, loading = false)
    }

    var releases by mutableStateOf<List<NewRelease>>(emptyList()); private set
    init {
        load(); loadAlbums()
        viewModelScope.launch {
            repeat(60) {
                if (owner != prefs.cachedUserId) return@launch
                val calendar = runCatching { api.releases().checked() }.getOrNull() ?: return@launch
                releases = calendar.items
                if (!calendar.preparing) return@launch
                kotlinx.coroutines.delay(5000)
            }
        }
    }

    fun releaseCover(release: NewRelease) = if (!release.hasCover) null else
        "${prefs.cachedAuth.serverUrl.trimEnd('/')}/api/home/releases/${release.id}/cover?account=${prefs.accountNamespace}"

    fun art(id: String?, size: Int = 300): String? = id?.let { library.getCoverArtUrl(it, size) }
    fun art(ref: CoverRef?, size: Int = 300): String? = when {
        ref == null -> null
        ref.cover != null -> ref.cover
        ref.source == "navidrome" -> library.getCoverArtUrl(ref.sourceId, size)
        ref.source == "youtube" -> "https://i.ytimg.com/vi/${ref.sourceId}/mqdefault.jpg"
        else -> null
    }
    private fun song(track: MusicTrack, cover: String?): Song =
        track.toSong().copy(coverArt = art(CoverRef(track.source, track.sourceId, cover), 128))

    fun load(): Job = viewModelScope.launch {
        if (owner != prefs.cachedUserId) return@launch
        runCatching { api.recentPlaylists().checked() }.onSuccess { recent = it.playlists }
        runCatching { api.homeArtists().checked() }.onSuccess { artists = it.artists }
        runCatching { api.homePlaylists().checked() }.onSuccess {
            val finished = status?.updating == true && !it.status.updating
            generated = it.playlists; status = it.status; unreachable = false
            if (finished) detail?.takeIf { d -> d.kind == "generated" }?.let { d -> fill(d) }
        }.onFailure { unreachable = true }
        loaded = true
        if (status?.updating == true && !polling) {
            polling = true
            delay(4000)
            polling = false
            load()
        }
    }
    private fun loadAlbums() = viewModelScope.launch {
        suspend fun shelf(type: String): List<Album> {
            val result = mutableListOf<Album>()
            var offset = 0
            do {
                val page = library.getAlbumList(type, 36, offset).getOrNull()?.albumList2 ?: break
                result += page.album.filter { it.name != page.defaultAlbum }
                offset += page.album.size
            } while (page.album.size == 36 && result.size < 12)
            return result.take(12)
        }
        frequent = shelf("frequent")
        newest = shelf("newest")
    }

    private suspend fun songs(kind: String, id: String): Pair<List<Song>, GeneratedPlaylist?> = when (kind) {
        "generated" -> api.homePlaylist(id).checked().let { list -> list.items.orEmpty().map { song(it.track, it.cover) } to list }
        "release" -> {
            var response = api.releaseTracks(id).checked()
            var polls = 0
            while (response.preparing && detail?.id == id && owner == prefs.cachedUserId) {
                delay(if (polls++ < 3) 400 else 2500)
                if (detail?.id != id || owner != prefs.cachedUserId) break
                response = api.releaseTracks(id).checked()
            }
            val releaseCover = detail?.takeIf { it.id == id }?.cover
            response.items.map { item -> item.track.toSong().copy(coverArt =
                if (item.track.source == "navidrome") item.track.sourceId else releaseCover) } to null
        }
        "mixed" -> api.playlist(id).checked().items.map { song(it.track, null) } to null
        else -> library.getPlaylist(id).getOrThrow().playlist?.entry.orEmpty() to null
    }
    private fun fill(target: HomeDetail) = viewModelScope.launch {
        try {
            val (songs, list) = songs(target.kind, target.id)
            if (detail?.id != target.id || detail?.kind != target.kind) return@launch
            detail = detail?.copy(songs = songs, loading = false, state = list?.state ?: "ready", updated = list?.updated,
                notice = list?.error, description = list?.description ?: target.description,
                cover = list?.covers?.firstOrNull()?.let { art(it, 400) } ?: target.cover)
            // Opening a list makes its first song the likely next press: have the server resolve
            // that one external source ahead (no audio is fetched and it is not a listen).
            list?.items?.firstOrNull()?.track?.takeIf { it.source == "youtube" }?.let { first ->
                runCatching { api.prepare(first.sourceId, owner) }
            }
        } catch (e: Exception) {
            if (detail?.id == target.id) detail = detail?.copy(loading = false, notice = e.message ?: "Servicio no disponible")
        }
    }
    fun open(kind: String, id: String, title: String, description: String = "", cover: String? = null) {
        val next = HomeDetail(kind, id, title, description, cover, weekly = kind == "generated" && id == "weekly")
        detail = next; fill(next)
    }
    fun close() { detail = null }
    fun playDetail(index: Int? = null) {
        val d = detail ?: return
        if (d.songs.isEmpty() || account != prefs.accountNamespace) return
        player.playQueue(d.songs, index ?: player.collectionStart(d.songs), playlistId = d.id.takeIf { d.kind in setOf("local", "mixed", "generated") }, playlistKind = d.kind)
    }
    fun play(kind: String, id: String) {
        val epoch = player.routeGuard.explicitPlay()
        viewModelScope.launch {
            try {
                val list = songs(kind, id).first
                if (list.isNotEmpty()) player.playQueue(list, player.collectionStart(list), requestEpoch = epoch, playlistId = id, playlistKind = kind)
                else message = "Esta lista todavia no tiene canciones."
            } catch (e: Exception) { message = e.message ?: "Servicio no disponible" }
        }
    }
    fun playAlbum(id: String) {
        val epoch = player.routeGuard.explicitPlay()
        viewModelScope.launch {
            library.getAlbum(id).onSuccess { r -> r.album?.song.orEmpty().takeIf { it.isNotEmpty() }?.let { player.playQueue(it, requestEpoch = epoch) } }
                .onFailure { message = it.message ?: "Servicio no disponible" }
        }
    }
    private fun act(done: String, work: suspend () -> Unit) {
        if (busy) return
        busy = true
        viewModelScope.launch {
            try { work(); message = done; load() }
            catch (e: Exception) { message = e.message ?: "Servicio no disponible" }
            finally { busy = false }
        }
    }
    fun save() = detail?.let { d -> act("Copia guardada en tu biblioteca") { api.saveGenerated(d.id, owner).checked() } }
    fun refresh() = act("Actualizando tus listas. La cola actual no cambia.") {
        val r = api.refreshHome(owner)
        if (r.code() == 429) throw IllegalStateException("Espera un minuto antes de volver a actualizar.")
        r.checked()
    }
    fun activate() = act("Lista semanal activada. Las primeras canciones pueden tardar unos minutos.") {
        val r = api.activateWeekly(owner)
        if (r.code() == 409) throw IllegalStateException("Todavia no hay artistas identificados en tus escuchas.")
        r.checked()
    }
}

@Composable
private fun Cover(url: String?, size: Dp?, modifier: Modifier = Modifier, shape: Shape = RoundedCornerShape(6.dp),
                  band: String? = null, bandKicker: String = "Mix", liked: Boolean = false) {
    val base = if (size != null) modifier.size(size) else modifier.fillMaxWidth().aspectRatio(1f)
    Box(base.clip(shape).background(if (liked) Brush.linearGradient(listOf(Color(0xFF5B2DD6), Color(0xFFA78BFA), Color(0xFFC9F2E4)))
        else Brush.linearGradient(listOf(Color(0xFF6D3FD0), Color(0xFF2B1C50)))), contentAlignment = Alignment.Center) {
        if (liked) Icon(Icons.Default.Favorite, null, tint = Color.White, modifier = Modifier.fillMaxSize(0.4f))
        else {
            Icon(Icons.Default.MusicNote, null, tint = Color.White.copy(alpha = 0.3f), modifier = Modifier.fillMaxSize(0.35f))
            if (url != null) AsyncImage(model = url, contentDescription = null, contentScale = ContentScale.Crop, modifier = Modifier.fillMaxSize())
        }
        if (band != null) {
            Box(Modifier.fillMaxSize().background(Brush.verticalGradient(listOf(Color(0x406D3FD0), Color(0xEB2B1250)))))
            Row(Modifier.align(Alignment.BottomStart).padding(10.dp).height(IntrinsicSize.Min)) {
                Box(Modifier.width(3.dp).fillMaxHeight().background(Accent))
                Column(Modifier.padding(start = 8.dp, end = 44.dp)) {
                    Text(bandKicker.uppercase(), color = Color.White.copy(alpha = 0.85f), fontSize = 9.sp, fontWeight = FontWeight.SemiBold, letterSpacing = 0.6.sp, maxLines = 1, softWrap = false)
                    Text(band, color = Color.White, fontSize = 16.sp, lineHeight = 18.sp, fontWeight = FontWeight.ExtraBold, maxLines = 2, overflow = TextOverflow.Ellipsis)
                }
            }
        }
    }
}

@Composable
private fun PlayDot(size: Dp, label: String, modifier: Modifier = Modifier, playing: Boolean = false, onClick: () -> Unit) {
    Box(modifier.size(size).clip(CircleShape).background(Accent).clickable(onClickLabel = label, onClick = onClick), contentAlignment = Alignment.Center) {
        Icon(if (playing) Icons.Default.Pause else Icons.Default.PlayArrow, label, tint = OnAccent, modifier = Modifier.size(size * 0.6f))
    }
}

@Composable
private fun QuickCard(title: String, modifier: Modifier, onOpen: () -> Unit, onPlay: () -> Unit, cover: @Composable () -> Unit) {
    Row(modifier.height(56.dp).clip(RoundedCornerShape(6.dp)).background(Color(0x14FFFFFF)).clickable(onClickLabel = "Abrir $title", onClick = onOpen),
        verticalAlignment = Alignment.CenterVertically) {
        cover()
        Text(title, Modifier.weight(1f).padding(horizontal = 8.dp), fontSize = 13.sp, lineHeight = 16.sp, fontWeight = FontWeight.Bold, maxLines = 2, overflow = TextOverflow.Ellipsis)
        PlayDot(32.dp, "Reproducir $title", Modifier.padding(end = 8.dp), onClick = onPlay)
    }
}

@Composable
private fun ShelfCard(title: String, subtitle: String, onOpen: () -> Unit, onPlay: (() -> Unit)?, cover: @Composable () -> Unit) {
    Column(Modifier.width(148.dp).clickable(onClickLabel = "Abrir $title", onClick = onOpen)) {
        Box {
            cover()
            if (onPlay != null) PlayDot(40.dp, "Reproducir $title", Modifier.align(Alignment.BottomEnd).padding(8.dp), onClick = onPlay)
        }
        Text(title, Modifier.padding(top = 10.dp), fontSize = 15.sp, fontWeight = FontWeight.Bold, maxLines = 1, overflow = TextOverflow.Ellipsis)
        Text(subtitle, color = Muted, fontSize = 13.sp, lineHeight = 17.sp, maxLines = 2, overflow = TextOverflow.Ellipsis)
    }
}

@Composable
private fun Heading(text: String, trailing: String? = null) {
    Row(Modifier.fillMaxWidth().padding(start = 16.dp, end = 16.dp, top = 24.dp, bottom = 12.dp), verticalAlignment = Alignment.CenterVertically) {
        Text(text, Modifier.weight(1f), fontSize = 22.sp, lineHeight = 26.sp, fontWeight = FontWeight.ExtraBold)
        if (trailing != null) Text(trailing, color = Accent, fontSize = 12.sp)
    }
}

@Composable
fun HomeScreen(onOpen: (String) -> Unit, vm: HomeViewModel = hiltViewModel()) {
    val snackbar = remember { SnackbarHostState() }
    LaunchedEffect(vm.message) { vm.message?.let { snackbar.showSnackbar(it); vm.message = null } }
    LaunchedEffect(Unit) { vm.loadOnPhone() }
    Box(Modifier.fillMaxSize()) {
        val detail = vm.detail
        if (detail != null) { BackHandler { vm.close() }; DetailView(detail, vm) } else HomeList(vm, onOpen)
        SnackbarHost(snackbar, Modifier.align(Alignment.BottomCenter))
    }
}

@Composable
private fun HomeList(vm: HomeViewModel, onOpen: (String) -> Unit) {
    val hour = remember { Calendar.getInstance().get(Calendar.HOUR_OF_DAY) }
    val greeting = if (hour < 6) "Buenas noches" else if (hour < 13) "Buenos dias" else if (hour < 21) "Buenas tardes" else "Buenas noches"
    fun mixLabel(name: String) = name.removePrefix("Mix ")
    LazyColumn(Modifier.fillMaxSize().statusBarsPadding(), contentPadding = PaddingValues(bottom = 32.dp)) {
        item { Text(greeting, Modifier.padding(start = 16.dp, end = 16.dp, top = 20.dp, bottom = 14.dp), fontSize = 24.sp, fontWeight = FontWeight.ExtraBold) }
        // Shortcuts: favourites first, then lists that were actually played, two per row.
        val quick: List<RecentPlaylist?> = listOf<RecentPlaylist?>(null) + vm.recent.take(7)
        items(quick.chunked(2)) { pair ->
            Row(Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 4.dp), horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                pair.forEach { p ->
                    if (p == null) QuickCard("Tus favoritos", Modifier.weight(1f), onOpen = { onOpen("favorites") }, onPlay = { onOpen("favorites") }) { Cover(null, 56.dp, shape = RoundedCornerShape(0.dp), liked = true) }
                    else QuickCard(p.name, Modifier.weight(1f),
                        onOpen = { if (p.kind == "local") onOpen("playlist/${p.id}") else vm.open(p.kind, p.id, p.name, cover = vm.art(p.covers?.firstOrNull(), 400)) },
                        onPlay = { vm.play(p.kind, p.id) }) {
                        Cover(p.coverArt?.let { vm.art(it, 160) } ?: vm.art(p.covers?.firstOrNull(), 160), 56.dp, shape = RoundedCornerShape(0.dp))
                    }
                }
                if (pair.size == 1) Spacer(Modifier.weight(1f))
            }
        }
        if (vm.loaded && vm.recent.isEmpty()) item { Text("Las playlists que escuches apareceran aqui.", Modifier.padding(horizontal = 16.dp, vertical = 8.dp), color = Muted, fontSize = 14.sp) }

        item { Heading("En el telefono") }
        item {
            QuickCard("Tus canciones sin conexion", Modifier.fillMaxWidth().padding(horizontal = 16.dp),
                onOpen = { vm.openOnPhone("all") }, onPlay = { vm.openOnPhone("all"); vm.playDetail() }) {
                Cover(vm.onPhone.firstOrNull()?.coverArt?.let { vm.art(it) }, 56.dp)
            }
        }
        items(vm.savedLists, key = { "phone:" + it.key }) { list ->
            QuickCard(list.title, Modifier.fillMaxWidth().padding(horizontal = 16.dp, vertical = 4.dp),
                onOpen = { vm.openOnPhone(list.key) }, onPlay = { vm.openOnPhone(list.key); vm.playDetail() }) {
                Cover(list.coverArt?.let { vm.art(it) }, 56.dp)
            }
        }

        item { Heading("Hecho para ti", if (vm.status?.updating == true) "Actualizando…" else null) }
        if (vm.generated.isNotEmpty()) item {
            LazyRow(contentPadding = PaddingValues(horizontal = 16.dp), horizontalArrangement = Arrangement.spacedBy(14.dp)) {
                items(vm.generated, key = { it.key }) { g ->
                    val cover = vm.art(g.covers?.firstOrNull(), 400)
                    ShelfCard(g.name, if (g.state == "inactive") "Activala para recibir canciones cada semana." else if (g.count > 0) g.description else "Todavia sin canciones disponibles.",
                        onOpen = { vm.open("generated", g.key, g.name, g.description, cover) },
                        onPlay = if (g.count > 0) ({ vm.play("generated", g.key) }) else null) {
                        Cover(cover, null, band = mixLabel(g.name), bandKicker = if (g.kind == "weekly") "Cada semana" else "Mix")
                    }
                }
            }
        } else item {
            val status = vm.status
            if (vm.loaded && vm.unreachable) Column(Modifier.padding(horizontal = 16.dp)) {
                Text("No se ha podido conectar con Armonia. Comprueba la conexion o la VPN; tus listas siguen guardadas.", color = Muted, fontSize = 14.sp)
                TextButton(onClick = { vm.load() }) { Text("Reintentar") }
            } else Text(when {
                !vm.loaded -> "Cargando tus listas…"
                status?.updating == true -> "Preparando tus listas a partir de lo que escuchas. Puede tardar un par de minutos."
                status?.error != null -> status.error
                status?.profile == "insufficient_profile" -> "Escucha musica durante unos dias y aqui apareceran listas hechas para ti."
                else -> "Todavia no hay listas para tu perfil. Se prepararan cuando haya artistas reconocidos en tus escuchas."
            }, Modifier.padding(horizontal = 16.dp), color = Muted, fontSize = 14.sp)
        }

        if (vm.releases.isNotEmpty()) {
            item { Heading("Novedades para ti") }
            for (upcoming in listOf(false, true)) {
                val rows = vm.releases.filter { it.upcoming == upcoming }
                if (upcoming && rows.isNotEmpty()) item { Heading("Proximamente") }
                if (rows.isNotEmpty()) item {
                    LazyRow(contentPadding = PaddingValues(horizontal = 16.dp), horizontalArrangement = Arrangement.spacedBy(14.dp)) {
                        items(rows, key = { it.id }) { release ->
                            val day = java.time.LocalDate.parse(release.date).format(
                                java.time.format.DateTimeFormatter.ofPattern("d MMM", Locale.forLanguageTag("es")))
                            val date = if (upcoming) "Sale el $day" else "Nuevo · $day"
                            val cover = vm.releaseCover(release)
                            ShelfCard(release.title, "${release.artist} · ${release.type} · $date", onOpen = {
                                if (upcoming) vm.message = date else vm.open("release", release.id, release.title, release.artist, cover)
                            }, onPlay = null) { Cover(cover, null) }
                        }
                    }
                }
            }
        }

        if (vm.artists.isNotEmpty()) {
            item { Heading("Artistas similares a los que escuchas") }
            item {
                LazyRow(contentPadding = PaddingValues(horizontal = 16.dp), horizontalArrangement = Arrangement.spacedBy(14.dp)) {
                    items(vm.artists, key = { it.channelId }) { a ->
                        ShelfCard(a.name, "Similar a ${a.similarTo.orEmpty()}", onOpen = { onOpen("ytartist/${a.channelId}") }, onPlay = null) { Cover(a.thumbnail, null, shape = CircleShape) }
                    }
                }
            }
        }
        listOf("Lo que mas escuchas" to vm.frequent, "Añadido recientemente a tu biblioteca" to vm.newest).forEach { (heading, albums) ->
            if (albums.isNotEmpty()) {
                item { Heading(heading) }
                item {
                    LazyRow(contentPadding = PaddingValues(horizontal = 16.dp), horizontalArrangement = Arrangement.spacedBy(14.dp)) {
                        items(albums, key = { it.id }) { album ->
                            ShelfCard(album.name, album.artist, onOpen = { onOpen("album/${album.id}") }, onPlay = null) { Cover(vm.art(album.coverArt, 300), null) }
                        }
                    }
                }
            }
        }
    }
}

@Composable
private fun DetailView(detail: HomeDetail, vm: HomeViewModel) {
    val current by vm.player.currentSong.collectAsState()
    val playing by vm.player.isPlaying.collectAsState()
    val generated = detail.kind == "generated"
    var menuFor by remember { mutableStateOf<Song?>(null) }
    menuFor?.let { song -> com.armonia.app.ui.components.SongMenuSheet(song, song.coverArt?.let { vm.art(it, 128) }, onDismiss = { menuFor = null }) }
    val updating = generated && vm.status?.updating == true
    val activeHere = detail.songs.any { it.id == current?.id }
    LazyColumn(Modifier.fillMaxSize(), contentPadding = PaddingValues(bottom = 32.dp)) {
        item {
            Column(Modifier.fillMaxWidth().background(Brush.verticalGradient(listOf(Color(0xFF6D3FD0), Color(0xFF2B1C50), Color(0xFF121015)))).statusBarsPadding().padding(16.dp)) {
                Box(Modifier.size(40.dp).clip(CircleShape).background(Color(0x4D000000)).clickable(onClickLabel = "Volver") { vm.close() }, contentAlignment = Alignment.Center) {
                    Icon(Icons.AutoMirrored.Filled.ArrowBack, "Volver", tint = Color.White)
                }
                Cover(detail.cover, 200.dp, Modifier.align(Alignment.CenterHorizontally).padding(vertical = 8.dp),
                    band = if (generated) detail.title.removePrefix("Mix ") else null, bandKicker = if (detail.weekly) "Cada semana" else "Mix")
                Text(if (generated) "HECHA PARA TI" else "LISTA", Modifier.padding(top = 12.dp), color = Color.White.copy(alpha = 0.75f), fontSize = 12.sp, fontWeight = FontWeight.SemiBold, letterSpacing = 1.sp)
                Text(detail.title, fontSize = 28.sp, lineHeight = 32.sp, fontWeight = FontWeight.ExtraBold)
                if (detail.description.isNotBlank()) Text(detail.description, Modifier.padding(top = 6.dp), color = Color.White.copy(alpha = 0.72f), fontSize = 14.sp)
                if (!detail.loading) {
                    val n = detail.songs.size
                    val date = detail.updated?.takeIf { n > 0 }?.let { " · Actualizada el " + SimpleDateFormat("d 'de' MMMM", Locale("es", "ES")).format(Date(it * 1000)) }.orEmpty()
                    Text("$n ${if (n == 1) "cancion" else "canciones"}$date", Modifier.padding(top = 4.dp), color = Color.White.copy(alpha = 0.6f), fontSize = 13.sp)
                    // A short weekly list is explained with the real counts, never padded.
                    val report = vm.status?.weekly
                    if (detail.weekly && report != null && report.listed < report.proposed)
                        Text("De ${report.proposed} canciones propuestas esta semana, ${report.listed} tienen una fuente disponible.", Modifier.padding(top = 4.dp), color = Color.White.copy(alpha = 0.6f), fontSize = 13.sp)
                }
            }
        }
        item {
            Row(Modifier.fillMaxWidth().padding(horizontal = 12.dp), verticalAlignment = Alignment.CenterVertically) {
                if (generated) {
                    IconButton(onClick = { vm.save() }, enabled = !vm.busy && detail.songs.isNotEmpty()) { Icon(Icons.AutoMirrored.Filled.PlaylistAdd, "Guardar una copia en tu biblioteca", tint = Muted) }
                    IconButton(onClick = { vm.refresh() }, enabled = !vm.busy && !updating) { Icon(Icons.Default.Refresh, "Actualizar esta lista", tint = Muted) }
                }
                Spacer(Modifier.weight(1f))
                com.armonia.app.ui.components.GlobalShuffle(vm.player)
                if (detail.songs.isNotEmpty()) PlayDot(56.dp, if (activeHere && playing) "Pausar" else "Reproducir ${detail.title}", Modifier.padding(start = 8.dp, end = 4.dp), playing = activeHere && playing) {
                    if (activeHere) vm.player.togglePlayPause() else vm.playDetail()
                }
            }
        }
        val notice = if (updating) "Actualizando esta lista…" else detail.notice
        if (notice != null && detail.songs.isNotEmpty()) item { Text(notice, Modifier.padding(horizontal = 16.dp, vertical = 8.dp), color = Accent, fontSize = 13.sp) }
        when {
            detail.loading -> item { Box(Modifier.fillMaxWidth().padding(32.dp), contentAlignment = Alignment.Center) { CircularProgressIndicator(color = Accent) } }
            detail.songs.isEmpty() -> item {
                Column(Modifier.fillMaxWidth().padding(24.dp), horizontalAlignment = Alignment.CenterHorizontally) {
                    if (generated && detail.state == "inactive") {
                        Text("Tu lista semanal reune canciones de artistas similares a los que mas escuchas.", color = Muted)
                        Button(onClick = { vm.activate() }, enabled = !vm.busy, modifier = Modifier.padding(top = 14.dp),
                            colors = ButtonDefaults.buttonColors(containerColor = Accent, contentColor = OnAccent)) { Text("Activar lista semanal", fontWeight = FontWeight.Bold) }
                    } else Text(notice ?: "Esta lista todavia no tiene canciones disponibles.", color = Muted)
                }
            }
            else -> itemsIndexed(detail.songs) { index, song ->
                val active = song.id == current?.id
                Row(Modifier.fillMaxWidth().clickable(onClickLabel = "Reproducir ${song.title}") { vm.playDetail(index) }.padding(horizontal = 16.dp, vertical = 6.dp), verticalAlignment = Alignment.CenterVertically) {
                    Cover(song.coverArt?.let { vm.art(it, 128) }, 48.dp, shape = RoundedCornerShape(4.dp))
                    Column(Modifier.weight(1f).padding(start = 12.dp)) {
                        Text(song.title, color = if (active) Accent else Color.Unspecified, fontSize = 16.sp, maxLines = 1, overflow = TextOverflow.Ellipsis)
                        Text(song.artist, color = Muted, fontSize = 14.sp, maxLines = 1, overflow = TextOverflow.Ellipsis)
                    }
                    IconButton(onClick = { menuFor = song }) { Icon(Icons.Default.MoreVert, "Opciones de ${song.title}", tint = Muted) }
                }
            }
        }
    }
}


internal fun songsOnPhone(available: Set<String>, metadata: Map<String, Song>): List<Song> =
    available.map { id -> metadata[id] ?: MusicTrack("navidrome", id, id, "").toSong() }
        .sortedBy { it.title.lowercase() }
